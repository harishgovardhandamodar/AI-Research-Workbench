"""Verification job runner for ft-validate.

``run_rag_verification`` launches the heavy work (RAG retrieval + base/adapter
generation + scoring) as a background subprocess and returns a ``run_id``
immediately. Poll ``get_validation_report``/``list_validation_runs`` for status.

The generated runner script supports three generation modes:

- ``hf``       — Unsloth (or transformers + PEFT) loads base + adapter and
                 answers each question (add ``max_new_tokens``).
- ``ollama``   — a local Ollama endpoint answers with base and adapter models.
- ``evidence`` — deterministic offline fallback: answers are drawn from the
                 retrieved chunks (keeps the pipeline testable with no GPU).

Scoring is always rule-based (see ``scoring.py``), with optional judge critiques.
"""

from __future__ import annotations

