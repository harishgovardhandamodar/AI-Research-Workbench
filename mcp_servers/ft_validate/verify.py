# --- generation backends ----------------------------------------------------

HF_GEN = '''
def gen_hf(model_spec):
    from transformers import AutoModelForCausalLM, AutoTokenizer
    base = model_spec.get("base") or model_spec.get("path")
    adapter_path = model_spec.get("path") if model_spec.get("kind") == "adapter" else None
    if adapter_path:
        # The adapter may have resized embeddings (e.g. new tokens added during
        # finetuning), so load the tokenizer from the adapter dir and grow the
        # base model's embedding/lm_head to match BEFORE attaching the adapter.
        # Use len(tokenizer) — it includes added tokens (vocab_size is just the
        # base vocab, e.g. 128000 vs len 128257). Training saved untied weights
        # (embed 128257 / lm_head 128256), so restore lm_head to its original
        # size after resizing.
        tokenizer = AutoTokenizer.from_pretrained(adapter_path)
        model = AutoModelForCausalLM.from_pretrained(base, device_map="auto")
        lm_orig = model.get_output_embeddings().weight.shape[0]
        if model.get_input_embeddings():
            model.resize_token_embeddings(len(tokenizer))
        from peft import PeftModel
        import torch as _torch
        cur_lm = model.get_output_embeddings().weight.shape[0]
        if cur_lm != lm_orig:
            wt = model.get_output_embeddings().weight
            head = _torch.nn.Linear(wt.shape[1], lm_orig, bias=False,
                                    dtype=wt.dtype).to(wt.device)
            with _torch.no_grad():
                head.weight.copy_(wt.detach()[:lm_orig])
            model.set_output_embeddings(head)
        model = PeftModel.from_pretrained(model, adapter_path)
    else:
        tokenizer = AutoTokenizer.from_pretrained(base)
        model = AutoModelForCausalLM.from_pretrained(base, device_map="auto")
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    def answer(question, evidence):
        ctx = "\\n".join(evidence[:3]) or "No context."
        prompt = f"Context:\\n{{ctx}}\\n\\nQuestion: {{question}}\\nAnswer:"
        inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
        out = model.generate(**inputs, max_new_tokens=MAX_NEW_TOKENS,
                             do_sample=False)
        text = tokenizer.decode(out[0][inputs["input_ids"].shape[1]:],
                                skip_special_tokens=True)
        return text.strip()[:2000]
    return answer
'''

OLLAMA_GEN = '''
def gen_ollama(model_spec):
    import urllib.request
    host = os.environ.get("OLLAMA_HOST", "http://127.0.0.1:11434")
    model_name = model_spec.get("ollama_name") or model_spec.get("path")
    def answer(question, evidence):
        ctx = "\\n".join(evidence[:3]) or "No context."
        prompt = f"Context:\\n{{ctx}}\\n\\nQuestion: {{question}}\\nAnswer:"
        body = json.dumps({"model": model_name, "prompt": prompt, "stream": False,
                           "options": {"temperature": 0.1, "num_predict": MAX_NEW_TOKENS}}).encode()
        req = urllib.request.Request(host + "/api/generate", data=body,
                                     headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=300) as resp:
            data = json.loads(resp.read().decode())
        return (data.get("response") or "").strip()[:2000]
    return answer
'''

EVIDENCE_GEN = '''
def gen_evidence(model_spec):
    """Deterministic offline answerer: answers from retrieved evidence."""
    def answer(question, evidence):
        if not evidence:
            return "(no evidence retrieved)"
        # Head of evidence, plus a keyword-leading summary for determinism.
        lead = evidence[0].strip()
        return lead[:1400] if lead else "(empty evidence)"
    return answer
'''

RUNNER_MAIN = '''
def main():
    import importlib.util
    sys.path.insert(0, {repo_root!r})
    from mcp_servers.ft_validate.rag import retrieve
    from mcp_servers.ft_validate import scoring

    store = _store()
    store.update_run(RUN_ID, status="running")

    # Build generators per model.
    gens = {{}}
    for ms in MODELS:
        mid = ms["model_id"]
        if GENERATION == "hf":
            gens[mid] = gen_hf(ms)
        elif GENERATION == "ollama":
            gens[mid] = gen_ollama(ms)
        else:
            gens[mid] = gen_evidence(ms)

    es = store.get_evalset(EVAL_SET_ID)
    if es is None:
        store.update_run(RUN_ID, status="failed",
                         error=f"eval set not found: {{EVAL_SET_ID}}")
        return

    per_question = []
    for i, q in enumerate(es.questions):
        _log(f"[{{i+1}}/{{len(es.questions)}}] {{q.question[:80]}}")
        ev = retrieve(store, INDEX_ID, q.question, top_k=TOP_K)
        ev_snippets = [e["text"] for e in ev]
        ev_ids = [e["chunk_id"] for e in ev]
        rec = {{
            "question_id": q.id, "question": q.question,
            "gold_answer": q.gold_answer,
            "evidence_chunk_ids": ev_ids,
            "evidence_snippets": ev_snippets,
            "base": None, "adapter": None,
        }}
        for mid, gen in gens.items():
            answer = gen(q.question, ev_snippets)
            rec[mid] = answer
            key = f"{{mid}}_scores"
            rec[key] = scoring.score_answer(answer, ev_snippets, q.gold_answer)
        base = rec.get("base") or ""
        adapter = rec.get("adapter")
        if adapter:
            rec["adapter_scores"]["retention"] = round(
                1.0 - scoring.answer_drift(base, adapter), 4)
            rec["delta"] = {{k: round((rec.get("adapter_scores") or {{}}).get(k, 0.0)
                                       - (rec.get("base_scores") or {{}}).get(k, 0.0), 4)
                             for k in ("faithfulness", "accuracy", "hallucination")}}
        per_question.append(rec)

    agg_base = scoring.aggregate_scores(per_question, "base")
    agg_adapter = scoring.aggregate_scores(per_question, "adapter") if any(r.get("adapter") for r in per_question) else {{}}
    failures = scoring.rank_failures(per_question, "faithfulness", 10)
    run = store.update_run(
        RUN_ID, status="done", per_question=per_question,
        aggregate={{"base": agg_base, "adapter": agg_adapter}},
        failures=failures)
    _log("VERIFICATION_DONE questions=" + str(len(per_question)))

if __name__ == "__main__":
    try:
        main()
    except Exception:
        _log("FAILED: " + traceback.format_exc())
        store = _store()
        store.update_run(RUN_ID, status="failed",
                         error=traceback.format_exc()[-2000:])
        sys.exit(1)
'''


def _repo_root() -> str:
    return str(Path(__file__).resolve().parents[2])


def _write_shim(store: ValidateStore) -> Path:
    shim = store.root / "_store_shim.py"
    shim.write_text(STORE_SHIM.format(repo_root=_repo_root()), encoding="utf-8")
    return shim


def run_rag_verification(store: ValidateStore, eval_set_id: str,
                         index_id: str, model_ids: list[str] | None = None,
                         base_model: str = "", adapter_path: str = "",
                         top_k: int = 5, judge_model: str = "",
                         generation: str = "", max_new_tokens: int = 256,
                         run_id: str | None = None) -> dict:
    """Launch a verification run in the background. Returns run_id immediately.

    ``generation`` is auto-detected (hf/ollama/evidence) unless provided.
    """
    es = store.get_evalset(eval_set_id)
    if es is None:
        raise ValueError(f"eval set not found: {eval_set_id} — run "
                         "generate_eval_set first")
    data = store.get_rag_index(index_id)
    if data is None:
        raise ValueError(f"RAG index not found: {index_id} — run "
                         "build_rag_index first")
    if not generation:
        from .inference import generation_mode
        generation = generation_mode(store, base_model, adapter_path)
    if generation not in ("hf", "ollama", "evidence"):
        raise ValueError(f"unknown generation mode '{generation}'")

    # In ollama mode base_model/adapter_path are *model names* (e.g.
    # "qwen3.6:latest"), not disk paths, so skip the on-disk adapter check.
    ollama = generation == "ollama"
    model_ids = list(model_ids) if model_ids else (
        ["base"] + (["adapter"] if adapter_path else []))
    models: list[dict] = []
    for mid in model_ids:
        if mid == "adapter":
            if not adapter_path:
                continue
            models.append({"model_id": "adapter", "kind": "adapter",
                           "path": adapter_path if ollama else _safe(adapter_path),
                           "base": base_model or ""})
        elif mid == "base":
            models.append({"model_id": "base", "kind": "base",
                           "path": base_model or ""})
        else:
            raise ValueError(f"unknown model id '{mid}' (expected 'base' or "
                             "'adapter')")
    if not models:
        raise ValueError("no models to evaluate (pass model_ids or base_model)")

    rid = run_id or uuid.uuid4().hex[:12]
    log_path = store.root / "runs" / f"{rid}.log"
    run = ValidationRun(
        id=rid, eval_set_id=eval_set_id, base_model=base_model,
        adapter_path=adapter_path, model_ids=model_ids, status="queued",
        created_at=time.time(), updated_at=time.time(),
        log_path=str(log_path))
    store.save_run(run)

    script = RUNNER_HEADER.format(
        store_root=str(store.root), run_id=rid, eval_set_id=eval_set_id,
        index_id=index_id, models_json=json.dumps(models), top_k=top_k,
        max_new_tokens=max_new_tokens, judge_model=judge_model,
        generation=generation)
    gen_src = {"hf": HF_GEN, "ollama": OLLAMA_GEN, "evidence": EVIDENCE_GEN}[generation]
    body = script + gen_src + RUNNER_MAIN.format(repo_root=_repo_root())
    script_path = store.root / "runs" / f"{rid}.py"
    script_path.write_text(body, encoding="utf-8")
    _write_shim(store)

    env = dict(os.environ)
    env["PYTHONUNBUFFERED"] = "1"
    logf = open(log_path, "w", encoding="utf-8")
    proc = subprocess.Popen([_python(), str(script_path)],
                            stdout=logf, stderr=subprocess.STDOUT, env=env,
                            cwd=str(store.root))
    _watch(rid, store, proc, logf)
    return {"run_id": rid, "status": "queued", "generation": generation,
            "model_ids": model_ids}


def _safe(path: str) -> str:
    p = Path(path).expanduser().resolve()
    if not p.exists():
        raise ValueError(f"adapter path does not exist: {path}")
    return str(p)


def _python() -> str:
    return shutil.which("python") or sys.executable


def _watch(run_id: str, store: ValidateStore, proc: subprocess.Popen, logf) -> None:
    import threading

    def _run():
        try:
            rc = proc.wait()
        finally:
            try:
                logf.close()
            except Exception:  # noqa: BLE001
                pass
        if rc != 0:
            tail = _read_tail(Path(store.root) / "runs" / f"{run_id}.log")
            store.update_run(run_id, status="failed",
                             error=tail[-1500:] or "unknown error")

    threading.Thread(target=_run, daemon=True).start()


def _read_tail(path: Path, n: int = 2000) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")[-n:]
    except Exception:  # noqa: BLE001
        return ""


def get_validation_report(store: ValidateStore, run_id: str,
                          format: str = "json") -> dict:
    """Poll a run: status, aggregate, failures, and the report text."""
    run = store.get_run(run_id)
    if run is None:
        raise ValueError(f"run not found: {run_id} — run "
                         "run_rag_verification or list_validation_runs")
    if run.status == "done" and run.report_path:
        md = Path(run.report_path).read_text(encoding="utf-8", errors="replace") \
            if Path(run.report_path).exists() else ""
    else:
        md = ""
    return {"run_id": run.id, "status": run.status, "eval_set_id": run.eval_set_id,
            "base_model": run.base_model, "adapter_path": run.adapter_path,
            "aggregate": run.aggregate, "failures": run.failures,
            "per_question_count": len(run.per_question),
            "error": run.error,
            "log_tail": _read_tail(Path(run.log_path)) if run.log_path else "",
            "report_md": md}


def list_validation_runs(store: ValidateStore) -> dict:
    return {"runs": store.list_runs()}
