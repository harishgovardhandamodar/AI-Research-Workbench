"""LoRA/QLoRA training runner + job system for dk-lora.

Training is long-running and must NOT block the MCP server, so it is launched as
a background subprocess and tracked as a job in the workspace:

  jobs/<id>.json        status/result
  jobs/<id>.log         streaming log tail (for get_training_status)

The generated script prefers Unsloth and falls back to TRL + PEFT. A ``toy``
mode trains a tiny PyTorch MLP so the whole pipeline is testable on CPU with no
model downloads — useful for integration tests and hardware-less smoke runs.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import time
import uuid
from pathlib import Path
from typing import Any

from .models import Dataset, JobRecord, TrainingConfig
from .store import Workspace

SCRIPT_HEADER = '''\
"""Generated by dk-lora. Runs LoRA/QLoRA fine-tuning (Unsloth or TRL backend)."""
from __future__ import annotations
import json, os, sys, traceback

DATASET = {dataset_json!r}
OUT_DIR = {out_dir!r}
CONFIG = json.loads({config_json!r})

def _log(msg: str) -> None:
    print(msg, flush=True)

def _emit_metric(name: str, value: Any) -> None:
    _log(f"[dk-metric] {{name}}={{value}}")

'''

UNSLOTH_SCRIPT = '''
def run_unsloth(cfg):
    from unsloth import FastLanguageModel
    from datasets import load_dataset
    from trl import SFTTrainer
    from transformers import TrainingArguments

    _log("loading base model (unsloth): " + cfg["base_model"])
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=cfg["base_model"],
        max_seq_length=cfg["max_seq_length"],
        dtype=None,
        load_in_4bit=(cfg["quant"] == "4bit") or (cfg["quant"] == "8bit" and False),
    )
    if cfg["quant"] == "8bit":
        model, tokenizer = FastLanguageModel.from_pretrained(
            model_name=cfg["base_model"], max_seq_length=cfg["max_seq_length"],
            load_in_8bit=True)
    _log("building LoRA adapter")
    model = FastLanguageModel.get_peft_model(
        model,
        r=cfg["lora_r"],
        target_modules=cfg["target_modules"],
        lora_alpha=cfg["lora_alpha"],
        lora_dropout=cfg["lora_dropout"],
        bias=cfg["bias"],
        use_gradient_checkpointing=("unsloth" if cfg["use_gradient_checkpointing"] else False),
        random_state=cfg["random_state"],
    )

    ds = load_dataset("json", data_files=DATASET, split="train")
    def fmt(ex):
        if ex.get("text"):
            return ex["text"]
        return (
            "### Instruction: " + ex.get("instruction", "") + "\\n\\n"
            "### Input: " + ex.get("input", "") + "\\n\\n"
            "### Response: " + ex.get("output", "")
        )
    args = TrainingArguments(
        per_device_train_batch_size=cfg["per_device_batch_size"],
        gradient_accumulation_steps=cfg["gradient_accumulation_steps"],
        warmup_ratio=cfg["warmup_ratio"],
        num_train_epochs=cfg["epochs"],
        learning_rate=cfg["learning_rate"],
        fp16=not cfg["quant"] == "4bit",
        bf16=cfg["quant"] == "4bit",
        logging_steps=1,
        weight_decay=cfg["weight_decay"],
        lr_scheduler_type=cfg["lr_scheduler_type"],
        seed=cfg["random_state"],
        output_dir=OUT_DIR,
        report_to=[],
        save_strategy="no",
    )
    trainer = SFTTrainer(
        model=model, tokenizer=tokenizer, args=args, train_dataset=ds,
        formatting_func=fmt, max_seq_length=cfg["max_seq_length"],
    )
    _log("starting training")
    trainer.train()
    _log("saving adapter")
    model.save_pretrained(os.path.join(OUT_DIR, "adapter"))
    tokenizer.save_pretrained(os.path.join(OUT_DIR, "adapter"))
    _log("TRAINING_DONE")

'''

TRL_SCRIPT = '''
def run_trl(cfg):
    from transformers import AutoModelForCausalLM, AutoTokenizer, TrainingArguments
    from peft import LoraConfig, get_peft_model
    from trl import SFTTrainer
    from datasets import load_dataset

    _log("loading base model (transformers): " + cfg["base_model"])
    kwargs = {"device_map": "auto"}
    if cfg["quant"] == "4bit":
        from transformers import BitsAndBytesConfig
        kwargs["quantization_config"] = BitsAndBytesConfig(
            load_in_4bit=True, bnb_4bit_compute_dtype="bfloat16")
    elif cfg["quant"] == "8bit":
        from transformers import BitsAndBytesConfig
        kwargs["quantization_config"] = BitsAndBytesConfig(load_in_8bit=True)
    tokenizer = AutoTokenizer.from_pretrained(cfg["base_model"])
    model = AutoModelForCausalLM.from_pretrained(cfg["base_model"], **kwargs)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    model = get_peft_model(model, LoraConfig(
        r=cfg["lora_r"], lora_alpha=cfg["lora_alpha"],
        target_modules=cfg["target_modules"], lora_dropout=cfg["lora_dropout"],
        bias=cfg["bias"], task_type="CAUSAL_LM"))
    ds = load_dataset("json", data_files=DATASET, split="train")
    def fmt(ex):
        if ex.get("text"):
            return ex["text"]
        return (f"### Instruction: {{ex.get('instruction','')}}\\n\\n"
                f"### Input: {{ex.get('input','')}}\\n\\n"
                f"### Response: {{ex.get('output','')}}")
    args = TrainingArguments(
        per_device_train_batch_size=cfg["per_device_batch_size"],
        gradient_accumulation_steps=cfg["gradient_accumulation_steps"],
        warmup_ratio=cfg["warmup_ratio"], num_train_epochs=cfg["epochs"],
        learning_rate=cfg["learning_rate"], weight_decay=cfg["weight_decay"],
        output_dir=OUT_DIR, report_to=[], seed=cfg["random_state"],
        save_strategy="no", logging_steps=1)
    trainer = SFTTrainer(model=model, tokenizer=tokenizer, args=args,
                         train_dataset=ds, formatting_func=fmt,
                         max_seq_length=cfg["max_seq_length"])
    _log("starting training")
    trainer.train()
    _log("saving adapter")
    model.save_pretrained(os.path.join(OUT_DIR, "adapter"))
    tokenizer.save_pretrained(os.path.join(OUT_DIR, "adapter"))
    _log("TRAINING_DONE")

'''

TOY_SCRIPT = '''
def run_toy(cfg):
    """CPU-only smoke training: a tiny model fit to the dataset.

    Uses only the Python standard library so integration tests can exercise the
    whole training pipeline without torch / GPU / model downloads. It simulates
    epochs, emits [dk-metric] lines for status polling, and writes a PEFT-shaped
    adapter directory so export_adapter works end to end.
    """
    import hashlib, math, os, random
    random.seed(cfg["random_state"])

    rows = []
    for line in open(DATASET, encoding="utf-8"):
        line = line.strip()
        if line:
            rows.append(json.loads(line))
    if not rows:
        _log("ERROR: empty dataset")
        sys.exit(1)

    # Bag-of-words feature vectors (deterministic, stdlib-only).
    vocab: dict[str, int] = {}
    X, y = [], []
    for ex in rows:
        text = (ex.get("instruction", "") + " " + ex.get("input", "")).lower()
        vec = {}
        for w in text.split():
            i = vocab.setdefault(w, len(vocab))
            vec[i] = vec.get(i, 0) + 1
        X.append(vec)
        y.append(hash(ex.get("output", "")) % 4)  # 4 synthetic classes
    n = max(16, len(vocab))

    def sparse_dot(a, w):
        return sum(c * w.get(i, 0.0) for i, c in a.items()) + w.get("_b", 0.0)

    # "Weights" we train with SGD; loss is deterministic for status polling.
    w = {"_b": 0.0}
    steps = min(40, max(4, len(rows) * 2))
    for step in range(steps):
        total = 0.0
        for a, yi in zip(X, y):
            score = sparse_dot(a, w)
            pred = 1.0 / (1.0 + math.exp(-max(min(score, 20.0), -20.0)))
            err = pred - (1.0 if yi % 2 == 0 else 0.0)
            for i, c in a.items():
                w[i] = w.get(i, 0.0) - cfg["learning_rate"] * err * c
            total += (err * err) * 0.5
        if step % 5 == 0:
            _emit_metric("train_loss", round(total / max(1, len(rows)), 4))
    _log("TRAINING_DONE")
    adapter_dir = os.path.join(OUT_DIR, "adapter")
    os.makedirs(adapter_dir, exist_ok=True)
    with open(os.path.join(adapter_dir, "adapter_config.json"), "w") as f:
        json.dump({"r": cfg["lora_r"], "alpha": cfg["lora_alpha"],
                   "base_model": cfg["base_model"], "toy": True}, f)
    with open(os.path.join(adapter_dir, "adapter_model.bin"), "w") as f:
        f.write("toy-adapter-v1\\n")
    with open(os.path.join(adapter_dir, "special_tokens_map.json"), "w") as f:
        f.write('{"eos_token": "</s>"}\\n')

'''

_MAIN = '''
def main():
    cfg = CONFIG
    try:
        if cfg.get("_toy"):
            run_toy(cfg)
        elif cfg["backend"] == "unsloth":
            run_unsloth(cfg)
        else:
            run_trl(cfg)
    except Exception as e:  # noqa: BLE001
        _log("FAILED: %s" % traceback.format_exc())
        sys.exit(1)

if __name__ == "__main__":
    main()
'''


def _render_script(cfg: TrainingConfig, dataset_jsonl: str, out_dir: str,
                   toy: bool) -> str:
    body = TOY_SCRIPT if toy else (UNSLOTH_SCRIPT if cfg.backend == "unsloth"
                                   else TRL_SCRIPT)
    cfg_dict = cfg.model_dump()
    cfg_dict["_toy"] = toy
    return (SCRIPT_HEADER.format(dataset_json=dataset_jsonl, out_dir=out_dir,
                                 config_json=json.dumps(cfg_dict))
            + body + _MAIN)


def _write_dataset_jsonl(ws: Workspace, ds: Dataset, dataset_id: str) -> str:
    path = ws.datasets_dir / f"{dataset_id}.train.jsonl"
    with open(path, "w", encoding="utf-8") as f:
        for ex in ds.examples:
            f.write(json.dumps(ex.model_dump(), ensure_ascii=False) + "\n")
    return str(path)


def _python() -> str:
    """Best python for the training subprocess (prefer the current venv)."""
    return shutil.which("python") or sys.executable


def _sanity_check(cfg: TrainingConfig) -> str:
    ok, err = cfg.validate_config()
    if not ok:
        return err
    return ""


def configure_training(ws: Workspace, cfg: TrainingConfig) -> dict:
    """Validate + persist a TrainingConfig. Returns the config summary."""
    err = _sanity_check(cfg)
    if err:
        raise ValueError(err)
    if not cfg.output_dir:
        cfg.output_dir = str(ws.adapters_dir / f"run-{cfg.id}-{time.strftime('%Y%m%d-%H%M%S')}")
    ws.save_config(cfg)
    return {"config_id": cfg.id, "config": cfg.model_dump(),
            "output_dir": cfg.output_dir}


def start_training(ws: Workspace, config_id: str, dataset_id: str,
                   output_dir: str = "", toy: bool = False,
                   config: dict[str, Any] | None = None) -> dict:
    """Launch training in the background. Returns immediately with a job id.

    ``config`` may be an inline validated config dict (from configure_training's
    ``config`` field); otherwise ``config_id`` must resolve in the workspace.
    """
    if config is not None:
        cfg = TrainingConfig(**config)
    else:
        cfg = ws.get_config(config_id) if config_id else None
        if cfg is None:
            raise ValueError(f"config not found: {config_id} — run "
                             "configure_training first")
    err = _sanity_check(cfg)
    if err:
        raise ValueError(err)
    ds = ws.get_dataset(dataset_id)
    if ds is None or not ds.examples:
        raise ValueError(f"dataset not found or empty: {dataset_id} — run "
                         "generate_dataset first")
    if not output_dir:
        output_dir = cfg.output_dir or str(ws.adapters_dir / f"run-{cfg.id}")

    job_id = uuid.uuid4().hex[:12]
    out_dir = str(Path(output_dir).expanduser().resolve())
    Path(out_dir).mkdir(parents=True, exist_ok=True)
    dataset_jsonl = _write_dataset_jsonl(ws, ds, dataset_id)
    script = _render_script(cfg, dataset_jsonl, out_dir, toy=toy)
    script_path = ws.jobs_dir / f"{job_id}.py"
    script_path.write_text(script, encoding="utf-8")

    job = JobRecord(id=job_id, kind="training", status="running",
                    created_at=time.time(), updated_at=time.time(),
                    config={"config_id": cfg.id, "dataset_id": dataset_id,
                            "toy": toy, "backend": cfg.backend},
                    log_path=str(ws.jobs_dir / f"{job_id}.log"),
                    output_dir=out_dir)
    ws.add_job(job)

    env = dict(os.environ)
    env["PYTHONUNBUFFERED"] = "1"
    env.setdefault("TOKENIZERS_PARALLELISM", "false")
    logf = open(ws.jobs_dir / f"{job_id}.log", "w", encoding="utf-8")
    proc = subprocess.Popen(
        [_python(), str(script_path)],
        stdout=logf, stderr=subprocess.STDOUT, env=env,
        cwd=str(ws.root),
    )
    _watch(job_id, ws, proc, logf)
    return {"job_id": job_id, "status": "running", "output_dir": out_dir,
            "backend": cfg.backend, "toy": toy}


def _watch(job_id: str, ws: Workspace, proc: subprocess.Popen, logf) -> None:
    """Background watcher that mirrors the process exit into the job record."""
    import threading

    def _run():
        try:
            rc = proc.wait()
        finally:
            try:
                logf.close()
            except Exception:  # noqa: BLE001
                pass
        status = "done" if rc == 0 else "failed"
        fields: dict[str, Any] = {"status": status, "result": {"returncode": rc}}
        if rc != 0:
            fields["error"] = _read_tail(ws.jobs_dir / f"{job_id}.log", 800)
        ws.update_job(job_id, **fields)

    threading.Thread(target=_run, daemon=True).start()


def _read_tail(path: Path, n_chars: int = 2000) -> str:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
        return text[-n_chars:]
    except Exception:  # noqa: BLE001
        return ""


def get_training_status(ws: Workspace, job_id: str) -> dict:
    job = ws.get_job(job_id)
    if job is None:
        raise ValueError(f"job not found: {job_id} — run start_training or "
                         "list_jobs for valid ids")
    return {"job_id": job.id, "status": job.status, "kind": job.kind,
            "output_dir": job.output_dir, "error": job.error,
            "result": job.result,
            "log_tail": _read_tail(Path(job.log_path or ""))}


def cancel_training(ws: Workspace, job_id: str) -> dict:
    job = ws.get_job(job_id)
    if job is None:
        raise ValueError(f"job not found: {job_id}")
    if job.status not in ("queued", "running"):
        return {"job_id": job_id, "status": job.status,
                "message": "job already finished; nothing to cancel"}
    # Best-effort: kill any subprocess started for this job (matches by script).
    script = ws.jobs_dir / f"{job_id}.py"
    killed = False
    try:
        out = subprocess.run(["pgrep", "-f", str(script)],
                             capture_output=True, text=True, timeout=5)
        for pid in out.stdout.split():
            try:
                os.kill(int(pid), 9)
                killed = True
            except Exception:  # noqa: BLE001
                pass
    except Exception:  # noqa: BLE001
        pass
    ws.update_job(job_id, status="cancelled",
                  error="cancelled by user" if killed else "cancelled")
    return {"job_id": job_id, "status": "cancelled", "killed": killed}


def list_jobs(ws: Workspace) -> dict:
    return {"jobs": ws.list_jobs()}
