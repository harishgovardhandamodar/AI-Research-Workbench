"""Synthetic UPI transaction data generator.

Adapted from the workbench's ``upi-transactions-generator.ipynb`` to run
locally and deterministically: the notebook used the global legacy ``np.random``
stream and Kaggle paths; here every draw comes from a caller-supplied
``np.random.default_rng`` so results are reproducible from a seed and never
disturb other RNG consumers. The schema matches ``upi_transactions_2024.csv``
generated by the notebook (17 columns, realistic demographics + banking +
device/network + a rare fraud flag).
"""

from __future__ import annotations

from datetime import datetime, timedelta

import numpy as np
import pandas as pd


def hourly_distribution() -> np.ndarray:
    """Realistic hourly transaction probabilities (peaks 10-13 and 17-21)."""
    hours_prob = [0.013942, 0.009293, 0.007435, 0.004647, 0.004647, 0.007435,
                  0.013941, 0.023234, 0.032528, 0.041822, 0.055762, 0.065056,
                  0.069703, 0.060409, 0.046468, 0.051115, 0.055762, 0.074349,
                  0.078996, 0.083643, 0.074349, 0.065056, 0.037175, 0.023234]
    rounded = np.round(hours_prob, 3)
    rounded[np.argmax(rounded)] += 1.0 - rounded.sum()
    return rounded


