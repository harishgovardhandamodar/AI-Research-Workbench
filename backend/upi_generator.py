def get_amt(merchant_categories, age_groups, rng: np.random.Generator) -> np.ndarray:
    """Realistic per-row amounts driven by merchant category and age group."""
    amounts = []
    cats = list(merchant_categories)
    ages = list(age_groups)
    for i, category in enumerate(cats):
        age_group = ages[i] if ages else None
        rand = rng.random()
        if category == "Food":
            if rand < 0.40:
                amount = rng.lognormal(np.log(120), 0.6)
            elif rand < 0.80:
                amount = rng.lognormal(np.log(400), 0.5)
            else:
                amount = rng.lognormal(np.log(1200), 0.4)
        elif category == "Grocery":
            if rand < 0.30:
                amount = rng.lognormal(np.log(250), 0.5)
            elif rand < 0.70:
                amount = rng.lognormal(np.log(800), 0.6)
            else:
                amount = rng.lognormal(np.log(2000), 0.4)
        elif category == "Fuel":
            if rand < 0.40:
                amount = rng.lognormal(np.log(500), 0.3)
            elif rand < 0.70:
                amount = rng.lognormal(np.log(1200), 0.4)
            else:
                amount = rng.lognormal(np.log(3000), 0.3)
        elif category == "Entertainment":
            if rand < 0.50:
                amount = rng.lognormal(np.log(200), 0.4)
            elif rand < 0.80:
                amount = rng.lognormal(np.log(600), 0.5)
            else:
                amount = rng.lognormal(np.log(300), 0.6)
        elif category == "Shopping":
            if rand < 0.40:
                amount = rng.lognormal(np.log(500), 0.7)
            elif rand < 0.75:
                amount = rng.lognormal(np.log(1800), 0.6)
            else:
                amount = rng.lognormal(np.log(5000), 0.4)
        elif category == "Healthcare":
            if rand < 0.50:
                amount = rng.lognormal(np.log(400), 0.5)
            elif rand < 0.80:
                amount = rng.lognormal(np.log(300), 0.4)
            else:
                amount = rng.lognormal(np.log(1000), 0.5)
        elif category == "Education":
            if rand < 0.40:
                amount = rng.lognormal(np.log(1500), 0.6)
            elif rand < 0.75:
                amount = rng.lognormal(np.log(4000), 0.5)
            else:
                amount = rng.lognormal(np.log(8000), 0.4)
        elif category == "Transport":
            if rand < 0.50:
                amount = rng.lognormal(np.log(80), 0.6)
            else:
                amount = rng.lognormal(np.log(400), 0.6)
        elif category == "Utilities":
            if rand < 0.25:
                amount = rng.lognormal(np.log(300), 0.4)
            else:
                amount = rng.lognormal(np.log(2500), 0.6)
        else:  # Other
            amount = rng.lognormal(np.log(600), 0.8)
        multiplier = (_AGE_MULTIPLIERS.get(age_group) or {}).get(category, 1.0)
        amount *= multiplier
        amount = max(amount, 10.0)
        amount = min(amount, 100000.0)
        amounts.append(int(round(amount)))
    return np.array(amounts)


def generate_upi_set(n_records: int = 1000,
                     start_date: str = "2024-01-01",
                     end_date: str = "2024-12-31",
                     seed: int = 42) -> pd.DataFrame:
    """Deterministically generate a synthetic UPI transaction DataFrame with
    the notebook's schema. Reproducible from ``seed``."""
    rng = np.random.default_rng(seed)
    n = int(n_records)
    start = datetime.strptime(start_date, "%Y-%m-%d")
    end = datetime.strptime(end_date, "%Y-%m-%d")
    date_range = (end - start).days

    transaction_type = rng.choice(["P2P", "P2M", "Bill Payment", "Recharge"],
                                  size=n, p=[0.45, 0.35, 0.15, 0.05])
    merchant_categories = rng.choice(
        ["Food", "Grocery", "Fuel", "Entertainment", "Shopping",
         "Healthcare", "Education", "Transport", "Utilities", "Other"],
        size=n, p=[0.15, 0.20, 0.10, 0.08, 0.12, 0.05, 0.03, 0.08, 0.09, 0.10])
    sender_age = rng.choice(["18-25", "26-35", "36-45", "46-55", "56+"],
                            size=n, p=[0.25, 0.35, 0.25, 0.10, 0.05])
    receiver_age = rng.choice(["18-25", "26-35", "36-45", "46-55", "56+"],
                              size=n, p=[0.25, 0.35, 0.25, 0.10, 0.05])
    states = rng.choice(
        ["Maharashtra", "Karnataka", "Delhi", "Tamil Nadu", "West Bengal",
         "Gujarat", "Rajasthan", "Uttar Pradesh", "Andhra Pradesh",
         "Telangana"],
        size=n, p=[0.15, 0.12, 0.10, 0.10, 0.08, 0.08, 0.08, 0.12, 0.08, 0.09])
    banks = rng.choice(
        ["SBI", "HDFC", "ICICI", "Axis", "PNB", "Kotak", "IndusInd", "Yes Bank"],
        size=n, p=[0.25, 0.15, 0.12, 0.10, 0.10, 0.08, 0.10, 0.10])
    device_type = rng.choice(["Android", "iOS", "Web"], size=n,
                             p=[0.75, 0.20, 0.05])
    network_type = rng.choice(["4G", "5G", "WiFi", "3G"], size=n,
                              p=[0.60, 0.25, 0.10, 0.05])
    fraud_flag = rng.choice([0, 1], size=n, p=[0.998, 0.002])

    days = rng.integers(0, max(date_range, 1), size=n)
    hours = rng.choice(np.arange(24), size=n, p=hourly_distribution())
    minutes = rng.integers(0, 60, size=n)
    seconds = rng.integers(0, 60, size=n)
    timestamps = [start + timedelta(days=int(d), hours=int(h),
                                    minutes=int(m), seconds=int(s))
                  for d, h, m, s in zip(days, hours, minutes, seconds)]

    data = {
        "transaction id": [f"TXN{str(i).zfill(10)}" for i in range(1, n + 1)],
        "timestamp": timestamps,
        "transaction type": transaction_type,
        "merchant_category": merchant_categories,
        "amount (INR)": get_amt(merchant_categories, sender_age, rng),
        "transaction_status": rng.choice(["SUCCESS", "FAILED"], size=n,
                                         p=[0.95, 0.05]),
        "sender_age_group": sender_age,
        "receiver_age_group": receiver_age,
        "sender_state": states,
        "sender_bank": banks,
        "receiver_bank": rng.choice(
            ["SBI", "HDFC", "ICICI", "Axis", "PNB", "Kotak", "IndusInd",
             "Yes Bank"],
            size=n, p=[0.25, 0.15, 0.12, 0.10, 0.10, 0.08, 0.10, 0.10]),
        "device_type": device_type,
        "network_type": network_type,
        "fraud_flag": fraud_flag,
        "hour_of_day": [t.hour for t in timestamps],
        "day_of_week": [t.weekday() for t in timestamps],
        "is_weekend": [1 if t.weekday() >= 5 else 0 for t in timestamps],
    }
    return pd.DataFrame(data)


def generate_upi_csv(path, n_records: int = 50000,
                     start_date: str = "2024-01-01",
                     end_date: str = "2024-12-31",
                     seed: int = 42) -> Path:
    """Generate a synthetic UPI dataset and write it to ``path``."""
    from pathlib import Path
    path = Path(path)
    df = generate_upi_set(n_records=n_records, start_date=start_date,
                          end_date=end_date, seed=seed)
    df.to_csv(path, index=False)
    return path
