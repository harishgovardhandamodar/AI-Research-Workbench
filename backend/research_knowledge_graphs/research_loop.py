"""Research Workbench: domain-scoped autoresearch loops over the knowledge graph.

Each *scenario* is a research domain (arXiv topics + a lens). A scenario loop
chains the pieces that the vendored app and the workbench already provide:

    Phase 1  Build corpus   pool topics -> arXiv search -> import papers into
                            the knowledge graph
    Phase 2  Synthesize     autorefine a domain research report, scored by an
                            LLM reviewer (metric: report_score, higher better) —
                            the research analog of the experiment.py loop
    Phase 3  Experiments    pick the strongest corpus papers, turn their
                            extracted experiment specs into runnable
                            experiment.py files, then run a bounded improve loop
                            (metric keep/revert), the classic autoresearch loop
    Phase 4  Fold back      re-run synthesis with the replication results so the
                            final report reflects the experiments

State lives under <data_root>/scenarios/<scenario_id>/:

    scenario.json   config + corpus + loop results (persisted)
    report.md       best domain report so far
    log.md          append-only research log
    experiments/    per-paper experiment.py + results.md
    project/        ProjectStore DB recording loop runs (workbench data model)

The two sample scenarios shipped with the tool:

    autonomous-agents-security   Autonomous Agents & Security Lapses
    enterprise-ai-security       Enterprise AI Adoption & Security Lapses

Long-running loop endpoints are submitted through the router's job registry, so
the dashboard polls jobs instead of holding a fetch open.
"""

